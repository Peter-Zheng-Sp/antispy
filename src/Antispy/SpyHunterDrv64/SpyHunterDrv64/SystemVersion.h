#ifndef _H_SYSTEMVERSION_
#define _H_SYSTEMVERSION_

typedef enum _NTOS_VERSION {
	WINDOWS_NONE = 0,
	WINDOWS_XP_SP3,
	WINDOWS_2K3_SP2,
	WINDOWS_VISTA_2008_RTM,
	WINDOWS_VISTA_2008_SP1,
	WINDOWS_VISTA_2008_SP2,
	WINDOWS_7_2008R2_RTM,
	WINDOWS_7_2008R2_SP1,
	WINDOWS_8_2012_RTM,
	WINDOWS_81_2012R2,
	WINDOWS_81_2012R2_SP1,
	WINDOWS_10_TH1,
	WINDOWS_10_TH2,
	WINDOWS_10_RS1,
	WINDOWS_10_RS2,
	WINDOWS_10_RS3,
	WINDOWS_10_RS4,
	WINDOWS_10_RS5,
	WINDOWS_10_19H1,
	WINDOWS_10_19H2,
	WINDOWS_10_20H1,
	WINDOWS_10_20H2,
	WINDOWS_10_21H1,
	WINDOWS_10_21H2,
	WINDOWS_10_22H2,
	WINDOWS_11_21H2,
	WINDOWS_11_22H2,
	WINDOWS_11_23h2,
	WINDOWS_MAX_INDEX
} NTOS_VERSION;

#define OS_MAX_SUPPORT WINDOWS_11_23h2
#define OS_MIN_SUPPORT WINDOWS_7_2008R2_RTM
#define OS_IS_SUPPORTED(__XX__) (((__XX__) <= OS_MAX_SUPPORT) && ((__XX__) >= OS_MIN_SUPPORT))
#define OS_IS_VISTA_LOWER(__XX__) ((__XX__) < (WINDOWS_VISTA_2008_RTM))
#define OS_IS_WIN7_LOWER(__XX__) ((__XX__) < (WINDOWS_7_2008R2_RTM))
#define OS_IS_WIN8_LOWER(__XX__) ((__XX__) < (WINDOWS_8_2012_RTM))
#define OS_IS_WIN81_LOWER(__XX__) ((__XX__) < (WINDOWS_81_2012R2))
#define OS_IS_WIN10_LOWER(__XX__) ((__XX__) < (WINDOWS_10_TH1))

#define OS_IS_VISTA(__XX__) (((__XX__) >= WINDOWS_VISTA_2008_RTM) && ((__XX__) <= WINDOWS_VISTA_2008_SP2))
#define OS_IS_WIN7(__XX__) (((__XX__) >= WINDOWS_7_2008R2_RTM) && ((__XX__) <= WINDOWS_7_2008R2_SP1))
#define OS_IS_WIN8(__XX__) ((__XX__) == WINDOWS_8_2012_RTM)
#define OS_IS_WIN81(__XX__) (((__XX__) >= WINDOWS_81_2012R2) && ((__XX__) <= WINDOWS_81_2012R2_SP1))
#define OS_IS_WIN10(__XX__) (((__XX__) >= WINDOWS_10_TH1) && ((__XX__) <= WINDOWS_10_22H2))
#define OS_IS_WIN11(__XX__) (((__XX__) >= WINDOWS_11_21H2) && ((__XX__) <= WINDOWS_11_23h2))

#define OS_MAX_INDEX (OS_MAX_SUPPORT + 1)

BOOLEAN         SystemVersion_IsOsServerVersion(OSVERSIONINFOEXW OsInfo);
NTOS_VERSION    SystemVersion_ParseOsInfo2InternalVersion(OSVERSIONINFOEXW OsInfo);

#endif // _H_SYSTEMVERSION_
